/**
 * Returns a human-readable food name from a raw model label.
 * Falls back to auto-formatting if no mapping exists.
 */
export function formatFoodLabel(rawLabel: string): string {
  const key = rawLabel.toLowerCase().trim();

  // Direct lookup
  if (FOOD_LABEL_MAP[key]) return FOOD_LABEL_MAP[key];

  // Auto-format: replace underscores, title-case each word
  return key
    .replace(/_/g, " ")
    .replace(/\b\w/g, (c) => c.toUpperCase());
}
